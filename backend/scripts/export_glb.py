"""Run with Blender 4.x+: --background --python-exit-code 1 --python export_glb.py -- config.json.

OBJ is imported as coordinates matching glTF Y-up, then cropped and oriented in
glTF coordinates. Preview has arbitrary units; only reviewed models use metres.
"""
import json
import math
from pathlib import Path
import sys
import bpy
import bmesh
from mathutils import Vector, Euler, Matrix


def main():
    config = json.loads(Path(sys.argv[sys.argv.index("--") + 1]).read_text(encoding="utf-8"))
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    bpy.ops.wm.obj_import(filepath=config["input"], forward_axis="NEGATIVE_Z", up_axis="Y")
    objects = [obj for obj in bpy.context.scene.objects if obj.type == "MESH"]
    if not objects:
        raise ValueError("No mesh was produced by reconstruction")
    bpy.ops.object.select_all(action="DESELECT")
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.object.join()
    obj = bpy.context.object
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    # Blender is Z-up; GLB is Y-up. Work in GLB coordinates for Android controls.
    to_gltf = Matrix.Rotation(-math.pi / 2, 4, "X")
    from_gltf = to_gltf.inverted()
    points = [to_gltf @ v.co for v in obj.data.vertices]
    low = Vector(tuple(min(p[i] for p in points) for i in range(3)))
    high = Vector(tuple(max(p[i] for p in points) for i in range(3)))
    cal = config.get("calibration") if config["final"] else None
    if cal:
        crop_low = Vector(tuple(low[i] + (high[i] - low[i]) * cal["crop_min"][i] for i in range(3)))
        crop_high = Vector(tuple(low[i] + (high[i] - low[i]) * cal["crop_max"][i] for i in range(3)))
        bm = bmesh.new()
        bm.from_mesh(obj.data)
        remove = [v for v in bm.verts if any((to_gltf @ v.co)[i] < crop_low[i] - 1e-6 or
                                             (to_gltf @ v.co)[i] > crop_high[i] + 1e-6 for i in range(3))]
        bmesh.ops.delete(bm, geom=remove, context="VERTS")
        bm.to_mesh(obj.data)
        bm.free()
        if not obj.data.polygons:
            raise ValueError("Crop removed the entire mesh; widen the crop and retry")
        rotation = Euler(tuple(math.radians(cal["rotation_" + axis]) for axis in "xyz"), "XYZ").to_matrix().to_4x4()
        obj.data.transform(from_gltf @ rotation @ to_gltf)
    if len(obj.data.polygons) > config["max_faces"]:
        modifier = obj.modifiers.new("Mobile optimization", "DECIMATE")
        modifier.ratio = config["max_faces"] / len(obj.data.polygons)
        bpy.ops.object.modifier_apply(modifier=modifier.name)
    points = [to_gltf @ v.co for v in obj.data.vertices]
    low = Vector(tuple(min(p[i] for p in points) for i in range(3)))
    high = Vector(tuple(max(p[i] for p in points) for i in range(3)))
    extent = high - low
    if min(extent) < 1e-7:
        raise ValueError("Degenerate mesh; dimensions cannot be measured")
    scale = (cal["reference_cm"] / 100 / extent[{"width": 0, "height": 1, "depth": 2}[cal["reference_axis"]]]) if cal else 1.0
    centre = Vector(((low.x + high.x) / 2, low.y, (low.z + high.z) / 2))
    for vertex in obj.data.vertices:
        vertex.co = from_gltf @ ((to_gltf @ vertex.co - centre) * scale)
    obj.data.update()
    # Opaque indoor surfaces; keep texture/material UVs generated by OpenMVS.
    for material in obj.data.materials:
        if material and material.use_nodes:
            for node in material.node_tree.nodes:
                if node.type == "BSDF_PRINCIPLED":
                    node.inputs["Roughness"].default_value = 0.8
                    node.inputs["Metallic"].default_value = 0
    for image in bpy.data.images:
        if image.size[0] > 2048 or image.size[1] > 2048:
            factor = 2048 / max(image.size)
            image.scale(round(image.size[0] * factor), round(image.size[1] * factor))
    bpy.ops.export_scene.gltf(filepath=config["output"], export_format="GLB", use_selection=True, export_yup=True)
    triangles = sum(len(face.vertices) - 2 for face in obj.data.polygons)
    result = dict(width_cm=extent.x * scale * 100, height_cm=extent.y * scale * 100,
                  depth_cm=extent.z * scale * 100, polygon_count=triangles,
                  file_size_bytes=Path(config["output"]).stat().st_size, scale_confirmed=bool(cal),
                  units="metres" if cal else "arbitrary", source="photogrammetry")
    Path(config["metadata_output"]).write_text(json.dumps(result), encoding="utf-8")


if __name__ == "__main__":
    main()
